"""Step 1: generate the raw two-bar MIDI dataset and split it into train/val/test.

Every sample is generated by src/generation.py, retried (up to
SANITY_MAX_RETRIES_PER_SAMPLE times) against the validation rules in
src/validation.py until one passes, then humanized (small timing/velocity
jitter) and written out as a <sample_id>.mid + <sample_id>.json pair.

With the same --seed, this produces byte-identical MIDI and metadata to any
other run - see docs/REPRODUCING.md.

Usage:
    python scripts/01_generate_midi.py --outdir two_bar_dataset --target 11300
"""

import argparse
import random
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # so `import src.*` works regardless of cwd

from src.config import RNG_SEED, SanityStats
from src.generation import build_concepts, generate_one_sample
from src.validation import (
    apply_timing_jitter,
    derive_attributes,
    generate_valid_sample,
    sanitize_events,
    safe_mkdir,
    validate_dataset_distribution,
    write_sanity_report,
    write_split,
)


class _Namespace:
    """Turns a plain dict into an object with attribute access, so
    build_concepts (which expects basic_info/control_attributes objects, to
    stay symmetric with how the dataclasses are used during generation) can
    be called on the dict form these values take once serialized to JSON."""
    def __init__(self, values: Dict[str, Any]) -> None:
        self.__dict__.update(values)


def finalize_sample(entry: Dict[str, Any], rng: random.Random) -> Dict[str, Any]:
    basic, control = entry["basic_info"], entry["control_attributes"]

    events = apply_timing_jitter(entry["events"], rng, control)
    events = sanitize_events(events, basic["clip_duration_sec"])
    basic["num_notes"] = len(events)

    return {
        "basic_info": basic,
        "control_attributes": control,
        "derived_attributes": derive_attributes(events),
        "concepts": build_concepts(_Namespace(basic), _Namespace(control)),
        "events": events,
    }


def generate_one_sample_for_validation(rng: random.Random) -> Dict[str, Any]:
    return finalize_sample(generate_one_sample(rng), rng)


def split_entries(
    entries: List[Dict[str, Any]], seed: int, splits: Tuple[float, float, float] = (0.8, 0.1, 0.1),
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]], List[Dict[str, Any]]]:
    rng = random.Random(seed)
    rng.shuffle(entries)
    n_train = int(len(entries) * splits[0])
    n_val = int(len(entries) * splits[1])
    return entries[:n_train], entries[n_train:n_train + n_val], entries[n_train + n_val:]


def build_dataset(outdir: Path, target_total: int, seed: int = RNG_SEED, splits: Tuple[float, float, float] = (0.8, 0.1, 0.1)) -> None:
    rng = random.Random(seed)
    sanity = SanityStats()

    entries = [generate_valid_sample(rng, sanity, generate_one_sample_for_validation) for _ in range(target_total)]
    train, val, test = split_entries(entries, seed=seed, splits=splits)

    safe_mkdir(outdir)
    write_split(train, outdir / "train", "train")
    write_split(val, outdir / "val", "val")
    write_split(test, outdir / "test", "test")

    write_sanity_report(outdir, sanity, validate_dataset_distribution(sanity))

    print(f"[DONE] wrote train={len(train)}, val={len(val)}, test={len(test)}")
    print(f"[SANITY] attempts={sanity.attempts}, accepted={sanity.accepted}, rejected={sanity.rejected}")
    print(f"[SANITY] report={outdir / 'sanity_report.txt'}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--outdir", type=str, required=True)
    ap.add_argument("--target", type=int, default=3000, help="Number of accepted samples to generate (before train/val/test split)")
    ap.add_argument("--seed", type=int, default=RNG_SEED)
    args = ap.parse_args()

    build_dataset(outdir=Path(args.outdir), target_total=args.target, seed=args.seed)
